"""mkblob.py -- turn the linked modules into an assembler source file
and an image blob, then lay the blob into CPM.SYS.

    mkblob.py modimg.s --boot SEG NAME SEG FILE 'EXPORTS' [...]
    mkblob.py --syms LINKED BOOTSEG ressym.s
    mkblob.py --place LINKED modimg.bin BOOT.mod CPM.SYS

Each FILE is an l.out linked alone at SEG<<24.  Its loaded image goes
into modimg.bin, and cmain.c copies it into physical page MODPHYSPAGE
at cold boot.  Images are packed there on 256-byte boundaries, and each
segment is mapped onto its own slice with a limit that ends it.

--place loads the blob over the start of CPM.SYS's bss, which nothing
touches before cold boot has copied the images out and zeroed it:

    linked   | data | bss ............ |
    CPM.SYS  | data | blob ....... | bss' |    (bss' = what the blob
                                                  leaves uncovered)

So the images cost resident memory only where they outgrow bss, and
only until cold boot.

The boot module is the code only cold boot runs.  It links after
CPM.SYS, against --syms's absolute copy of CPM.SYS's globals, so it
calls and names them directly.  --place puts it past both the blob and
bss, on a 256-byte physical boundary, where cmain.c maps its segment
onto it in place.  Nothing uses that RAM afterwards.  CPM.SYS reaches
it through bootent_, the first bytes of its segment.

The module's EXPORTS become absolute symbols, taken from the same link
as the image, so CPM.SYS calls or names them like any other global.  A
Z8001 segmented CALL carries the full address and RET pops it, so
crossing into a module needs nothing more.
"""

import os
import re
import struct
import sys

L_SHRI, L_PRVI, L_BSSI, L_SHRD, L_PRVD, L_BSSD, L_DEBUG, L_SYM, L_REL = range(9)
SYMSZ = 22			# ldsym: 16 name + 2 type + 4 addr


def die(msg):
    sys.exit("mkblob: %s" % msg)


def gl(b, o):
    """One PDP-order (high word first, each word little-endian) long."""
    return (struct.unpack_from("<H", b, o)[0] << 16) | \
        struct.unpack_from("<H", b, o + 2)[0]


def cfg(name):
    txt = open("src/bios/c900cfg.h").read()
    m = re.search(r"#define\s+%s\s+(0x[0-9a-fA-F]+|\d+)" % name, txt)
    if not m:
        die("c900cfg.h defines no %s" % name)
    return int(m.group(1), 0)


def load(name, seg, modf):
    b = open(modf, "rb").read()
    if len(b) < 48:
        die("%s: too short for an l.out header" % modf)
    magic, flag, machine, tbase = struct.unpack_from("<hhhh", b, 0)
    if magic != 0o407:
        die("%s: bad l.out magic 0%o" % (modf, magic))
    ssize = [gl(b, 8 + 4 * i) for i in range(9)]

    # The image is copied as one block, so the loaded layout has to be
    # SHRI, SHRD and PRVD with nothing between them.  ld's baseall() puts
    # PRVI and BSSI between SHRI and SHRD when they are non-empty, and
    # BSSI in particular would land in the middle of what we copy.
    for s, sn in ((L_PRVI, "PRVI"), (L_BSSI, "BSSI")):
        if ssize[s]:
            die("%s: %s is %d bytes; the module image must be SHRI+SHRD+PRVD "
                "only (see the layout note in this script)"
                % (modf, sn, ssize[s]))

    imglen = ssize[L_SHRI] + ssize[L_SHRD] + ssize[L_PRVD]
    img = b[tbase:tbase + imglen]
    if len(img) != imglen:
        die("%s: file holds %d image bytes, header says %d"
            % (modf, len(img), imglen))

    syms = {}
    symoff = tbase + imglen + ssize[L_DEBUG]
    for i in range(ssize[L_SYM] // SYMSZ):
        o = symoff + i * SYMSZ
        nm = b[o:o + 16].split(b"\0")[0].decode("ascii", "replace")
        syms[nm] = gl(b, o + 18)
    return dict(name=name, seg=seg, img=img, text=ssize[L_SHRI],
                bss=ssize[L_BSSD], syms=syms)


def lsyms(b):
    """An l.out's symbol table: name -> (type, value)."""
    tbase = struct.unpack_from("<h", b, 6)[0]
    ssize = [gl(b, 8 + 4 * i) for i in range(9)]
    o = tbase + ssize[L_SHRI] + ssize[L_PRVI] + ssize[L_SHRD] + \
        ssize[L_PRVD] + ssize[L_DEBUG]
    syms = {}
    for i in range(ssize[L_SYM] // SYMSZ):
        p = o + i * SYMSZ
        nm = b[p:p + 16].split(b"\0")[0].decode("ascii", "replace")
        syms[nm] = (struct.unpack_from("<H", b, p + 16)[0], gl(b, p + 18))
    return syms


def ressyms(lnkf, bootseg, outf):
    """CPM.SYS's globals as absolute symbols, for the boot module's link."""
    with open(outf, "w") as f:
        f.write("/ Generated by tools/mkblob.py -- do not edit.\n")
        for nm, (ty, v) in sorted(lsyms(open(lnkf, "rb").read()).items()):
            if ty & 0x10 == 0 or nm == "SS" or v >> 24 == bootseg:
                continue
            f.write("\t.globl\t%s\n%s = 0x%08x\n" % (nm, nm, v))


def place(lnkf, binf, bootf, outf):
    b = open(lnkf, "rb").read()
    blob = open(binf, "rb").read()
    boot = load("boot", 0, bootf)
    tbase = struct.unpack_from("<h", b, 6)[0]
    ssize = [gl(b, 8 + 4 * i) for i in range(9)]
    doff = tbase + ssize[L_SHRI] + ssize[L_PRVI]
    ds = ssize[L_SHRD] + ssize[L_PRVD]
    pad = ds & 1

    # The boot module runs in place, so it starts on a 256-byte physical
    # boundary past both the blob and the bss cold boot fills in.  The
    # data segment's physical base is 1K-aligned.
    bo = max(ds + pad + len(blob), ds + pad + ssize[L_BSSD])
    bo = (bo + 255) & ~255
    tsz = ssize[L_SHRI] + ssize[L_PRVI]
    bpage = ((cfg("SYSPHYSPAGE") << 16) + ((tsz + 1023) & ~1023) + bo) >> 8
    bimg = boot["img"] + b"\0" * boot["bss"]
    grow = bo - ds + len(bimg)

    syms = dict((k, v) for k, (t, v) in lsyms(b).items())
    for nm in ("modblob_", "bootpg_", "bootlim_"):
        if nm not in syms:
            die("%s: %s is not in the symbol table" % (lnkf, nm))

    h = bytearray(b[:doff + ds])
    for s, n in ((L_PRVD, ssize[L_PRVD] + grow),
                 (L_BSSD, max(0, ssize[L_BSSD] - grow))):
        struct.pack_into("<HH", h, 8 + 4 * s, n >> 16, n & 0xFFFF)
    a = (syms["modblob_"] & 0xFFFFFF) + doff
    v = (syms["modblob_"] & 0xFF000000) + ds + pad
    struct.pack_into(">L", h, a, v)		# image bytes are big-endian
    struct.pack_into(">H", h, (syms["bootpg_"] & 0xFFFFFF) + doff, bpage)
    struct.pack_into(">H", h, (syms["bootlim_"] & 0xFFFFFF) + doff,
                     (len(bimg) + 255) // 256 - 1)
    img = b"\0" * pad + blob
    img += b"\0" * (bo - ds - len(img)) + bimg
    open(outf, "wb").write(bytes(h) + img + b[doff + ds:])
    print("boot.mod: text %d + data %d + bss %d, run in place at phys 0x%06x"
          % (boot["text"], len(boot["img"]) - boot["text"], boot["bss"],
             bpage << 8))


def main():
    if sys.argv[1:2] == ["--place"] and len(sys.argv) == 6:
        return place(*sys.argv[2:])
    if sys.argv[1:2] == ["--syms"] and len(sys.argv) == 5:
        return ressyms(sys.argv[2], int(sys.argv[3], 0), sys.argv[4])
    a = sys.argv[4:]
    if len(sys.argv) < 8 or sys.argv[2] != "--boot" or len(a) % 4:
        die("usage: mkblob.py modimg.s --boot SEG NAME SEG FILE 'EXPORTS' ...")
    outf = sys.argv[1]
    bootseg = int(sys.argv[3], 0)
    top = (cfg("MODLIM") + 1) * 256
    mods, off = [], 0
    for i in range(0, len(a), 4):
        name, seg, modf, exps = a[i], int(a[i + 1], 0), a[i + 2], a[i + 3]
        m = load(name, seg, modf)
        m["off"] = off
        m["size"] = len(m["img"]) + m["bss"]
        m["blocks"] = (m["size"] + 255) // 256
        m["exps"] = exps.split()
        for nm in m["exps"]:
            if nm not in m["syms"]:
                die("%s: exported symbol %s is not defined" % (modf, nm))
        off += m["blocks"] * 256
        mods.append(m)
    if off > top:
        die("modules need %d bytes; page 0x%02X holds %d"
            % (off, cfg("MODPHYSPAGE"), top))

    page = cfg("MODPHYSPAGE") << 8
    blob = b""
    for m in mods:
        m["boff"] = len(blob)
        blob += m["img"] + b"\0" * (len(m["img"]) & 1)
    open(os.path.splitext(outf)[0] + ".bin", "wb").write(blob)
    with open(outf, "w") as f:
        f.write("/ Generated by tools/mkblob.py -- do not edit.\n"
                "/ The linked modules' exports and where their images go;\n"
                "/ --place sets modblob_ to where the images load.\n\n")
        for m in mods:
            for nm in m["exps"]:
                f.write("\t.globl\t%s\n%s = 0x%08x\n"
                        % (nm, nm, m["syms"][nm]))
        f.write("\t.globl\tbootent_\nbootent_ = 0x%08x\n" % (bootseg << 24))
        f.write("\n\t.prvd\n\t.even\n\n"
                "\t.globl\tmodblob_\nmodblob_:\n\t.long\t0\n"
                "\t.globl\tmodlen_\nmodlen_:\n\t.word\t%d\n"
                "/ the boot module's segment, base page and limit\n"
                "\t.globl\tbootseg_\nbootseg_:\n\t.word\t0x%02x\n"
                "\t.globl\tbootpg_\nbootpg_:\n\t.word\t0\n"
                "\t.globl\tbootlim_\nbootlim_:\n\t.word\t0\n"
                "/ seg, base page, limit, image length, bss length, offset\n"
                "\t.globl\tmodn_\nmodn_:\n\t.word\t%d\n"
                "\t.globl\tmodtab_\nmodtab_:\n" % (len(blob), bootseg, len(mods)))
        for m in mods:
            f.write("\t.word\t0x%02x, 0x%04x, 0x%02x, %d, %d\n\t.long\t%d\n"
                    % (m["seg"], page + m["off"] // 256, m["blocks"] - 1,
                       len(m["img"]), m["bss"], m["boff"]))
    for m in mods:
        print("%s.mod: seg 0x%02x at phys 0x%06x, text %d + data %d + bss %d"
              " = %d bytes, %d free in its segment"
              % (m["name"], m["seg"], (page << 8) + m["off"], m["text"],
                 len(m["img"]) - m["text"], m["bss"], m["size"],
                 0x10000 - m["size"]))
    print("modules: %d of %d bytes in page 0x%02X"
          % (off, top, cfg("MODPHYSPAGE")))


main()
